"""
Prompt Builder Layer: формирование запроса к LLM.

Комбинирует системную инструкцию и пользовательский запрос
в единый промпт.
"""

# Системная инструкция — задаёт роль и поведение модели
SYSTEM_PROMPT = (
    "Ты — полезный ассистент. Отвечай ТОЛЬКО на русском языке. "
    "Отвечай кратко и по делу. "
    "Не используй вводные слова типа «Вот ответ», «body», «текст сообщения» и т.п. "
    "Не повторяй вопрос пользователя. "
    "Пиши сразу по существу."
)


def build_prompt(message: str, system_prompt: str = SYSTEM_PROMPT) -> str:
    """
    Формирует полный промпт для LLM.

    Args:
        message: пользовательское сообщение
        system_prompt: системная инструкция (по умолчанию стандартная)

    Returns:
        Полный промпт, готовый к отправке в LLM

    Пример результата:
        "Ты — полезный ассистент. Отвечай кратко и по делу.\n\nUser: Привет!"
    """
    prompt = f"{system_prompt}\n\nUser: {message}"
    return prompt
